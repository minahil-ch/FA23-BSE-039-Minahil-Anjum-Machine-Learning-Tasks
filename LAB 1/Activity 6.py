print("\n===== Activity 6: Operator Precedence Check =====")

# 1. ** Exponent
print("**  :", 2 ** 3, "  # 2  power 3 = 8")

# 2. % Modulus
print("%   :", 22 % 8, "  # 22 / 8  remainder = 6")

# 3. // Floor Division  
print("//  :", 22 // 8, "  # 22 / 8  = 2")

# 4. / Division
print("/   :", 22 / 8, "  # 22 / 8 = 2.75")

# 5. * Multiplication
print("*   :", 3 * 5, "  # 3 * 5 = 15")

# 6. - Subtraction
print("-   :", 5 - 2, "  # 5 - 2 = 3")

# 7. + Addition
print("+   :", 2 + 2, "  # 2 + 2 = 4")

print("\n===== Precedence Test =====")
# Test: 
print("2 + 3 * 4 ** 2 =", 2 + 3 * 4 ** 2)  # 2 + 3 * 16 = 2 + 48 = 50